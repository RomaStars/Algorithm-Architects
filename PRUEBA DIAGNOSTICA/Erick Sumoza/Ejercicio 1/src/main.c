void print_result(const char *ak, int n, const char *seq) {
    int error_type = 0;
    int failed = validate_sequence(ak, n, seq, &error_type);
    
    printf("Ak=%-3s | n=%-2d | Salida: ", ak, n);
    if (failed == 0) {
        printf("movimiento CORRECTO.\n");
    } else {
        if (error_type == 1) {
            printf("INCORRECTO falla letra %c no pertenece a un caballo.\n", seq[0]);
        } else {
            printf("INCORRECTO falla en el movimiento %d.\n", failed);
        }
    }
}

